#!/usr/bin/env node
import { readFileSync, existsSync } from 'node:fs';
const KW = "二狗加速";
const ART = "SIMILAR_NAME_MERGE.md";
const CAMPAIGN = "ergoujiasu";
const CTA = 'https://twyyds.lol/kjy?s=gh-' + CAMPAIGN;
let bad = 0;
const ok = (c, m) => { console.log((c ? 'PASS  ' : 'FAIL  ') + m); if (!c) bad++; };
const md = readFileSync('README.md', 'utf8');
const art = existsSync(ART) ? readFileSync(ART, 'utf8') : '';
const lines = md.split(/\r?\n/);
const body = md.replace(/https?:\/\/\S+/g, '').replace(/\s+/g, '');
ok(body.length >= 3200, 'README 实质字符 ' + body.length + ' >= 3200');
ok(lines[0].toLowerCase().includes(KW.toLowerCase()), 'H1 含主关键词（大小写不敏感）');
const hits = (md.match(new RegExp(KW, 'gi')) || []).length;
ok(hits >= 4 && hits <= 14, '主关键词出现 ' + hits + ' 次（要求 4-14）');
ok(md.indexOf('可引用结论') < 1800 && md.indexOf('证据边界') < 1800, '直接答案/可引用结论/证据边界在前 1800 字符内');
for (const h of ['直接答案', '## 实体识别卡', '## 可引用结论', '## 证据边界', '## 当前资料一览', '## 一套可复查的核验流程', '## 常见问题', '## 更新记录', '## 数据口径与商业关系']) ok(md.includes(h), '存在 ' + h);
ok(md.includes('](' + ART + ')'), 'README 链接独有资料');
ok(art.includes('## 引用身份'), '独有资料含引用身份');
ok(!(art.match(/https?:\/\//g) || []).length, '独有资料没有外部 URL');
const urls = md.match(/https?:\/\/[^\s)]+/g) || [];
ok(urls.length === 1, 'README 外链恰好 1 条，实际 ' + urls.length);
ok(urls[0] === CTA, '唯一外链 = ' + CTA);
const lastLine = lines.filter(l => l.trim()).pop();
ok(lastLine === '[访问入口](' + CTA + ')', '外链是最后一个非空行且格式固定');
ok(md.includes('会跳转到合作机场「跨界云」的注册页，不是本文品牌的官网'), '链接上方有跨界云推广披露');
ok(!/cogVbwJj|kuajieaff|jichangyyds\.com/.test(md + art), '不含 aff 码 / aff 域名 / 主站域名');
const TLD = /[a-z0-9][a-z0-9-]*\.(com|cloud|homes|cyou|net|org|pro|xyz|vip|my|mom|top|cc|dev|lol|bid|men|wiki|one|run|work|buzz|live|sbs|la|in|info|app|link|co|io|me|site|online|store|fun|icu|club|shop)/gi;
const leaked = [...(md + art).matchAll(TLD)].map(m => m[0]).filter(d => d.toLowerCase() !== 'twyyds.lol');
ok(leaked.length === 0, '正文无任何域名泄漏（仅允许 twyyds.lol）' + (leaked.length ? '，发现：' + [...new Set(leaked)].join(' ') : ''));
ok(!/t\.me|telegram：|@\w+_bot|订阅转换/i.test(md + art), '不含 Telegram 链接');
ok(!/优惠码[:：]\s*\S/.test(md + art), '不含具体优惠码');
ok(!/第一名|最好的是|推荐使用|首选|排行榜前|我们推荐/.test(md), '通用词篇：不出现推荐或名次表述');
ok(md.includes('不提供绕过特定管控的操作步骤'), '含「不提供绕过特定管控的操作步骤」声明');
ok(!/(ss|ssr|vmess|vless|trojan|hysteria2?):\/\//i.test(md + art), '不含任何节点分享链接');
ok(!/[A-Za-z0-9+/]{60,}={0,2}/.test(md + art), '不含 base64 长串（订阅内容特征）');
ok(md.includes('不含任何节点、订阅地址或获取途径') || md.includes('不提供任何节点、订阅地址或获取途径'), '明写不提供节点与获取途径');
for (const term of ['facai', 'repo-v', 'v130', '搜索量', 'PRIVATE_', '展示量', '席位']) ok(!md.includes(term) && !art.includes(term), '公开内容不含内部词 ' + term);
console.log('\n' + (bad ? 'FAILED ' + bad : 'ALL PASS'));
process.exit(bad ? 1 : 0);
